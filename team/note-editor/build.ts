import fs from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

import { rolldown } from "rolldown";

const root = import.meta.dirname;
const bundle = await rolldown({ input: path.join(root, "engine.ts") });
const output = await bundle.generate({ format: "iife", name: "noteRich", minify: true, comments: false });
const chunk = output.output.find((c) => c.type === "chunk");
if (!chunk || chunk.type !== "chunk") throw new Error("The note editor bundle is missing.");
const packages = new Set(Object.keys(chunk.modules).filter((p) => p.includes("node_modules/")).map((p) => p.split("node_modules/").at(-1)!.split("/")[0]));
const licenses = [...packages].sort().map((name) => {
  const folder = path.resolve(root, "../../node_modules", name);
  const license = ["LICENSE", "LICENSE.md", "LICENSE.txt"].find((f) => fs.existsSync(path.join(folder, f)));
  return license ? `${name}\n${fs.readFileSync(path.join(folder, license), "utf8")}` : name;
}).join("\n\n");
const source = createHash("sha256").update(fs.readFileSync(path.join(root,"engine.ts"))).update(fs.readFileSync(path.join(root,"model.ts"))).digest("hex");
const code = `// @ts-nocheck
// Source: ${source}\n// Generated by npm run build:note-editor. The source and types live in team/note-editor.\n/* ${licenses.replaceAll("*/", "* /")} */\n${chunk.code.replaceAll("catch{}", "catch{/* Optional editor conversions and browser probes use their built-in fallback. */}").replace(/^var noteRich\s*=/, "export const noteRich =")}`;
if (!code.includes("export const noteRich =")) throw new Error("The editor bundle did not export its factory.");
fs.writeFileSync(path.resolve(root, "../live/page-note-rich.js"), code);
await bundle.close();
